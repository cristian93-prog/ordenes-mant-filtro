const ATENCION_NEG_WORDS = 'FUGA|FUGAS|PROBLEMA|PROBLEMAS|NOVEDAD|NOVEDADES|DANO|DANOS|ANOMALIA|ANOMALIAS|FALLA|FALLAS|RUIDO|RUIDOS|DESGASTE|PENDIENTE|PENDIENTES|OBSERVACION|OBSERVACIONES|CAMBIO|REPARACION|ATENCION|MANTENIMIENTO|REPUESTO|REPUESTOS|GOTEO|VIBRACION|VIBRACIONES|ALARMA|ALARMAS|PERDIDA|PERDIDAS|CORTOCIRCUITO|FILTRACION|FILTRACIONES|DEFECTO|DEFECTOS|IRREGULARIDAD|IRREGULARIDADES|DETERIORO|HOLGURA|HOLGURAS|ROTURA|ROTURAS|FALLO|RUPTURA|CORROSION|SOBRECALENTAMIENTO|DANADO|DANADOS|DANADA|DANADAS|ROTO|ROTA|ROTOS|ROTAS|QUEMADO|QUEMADA|DESGASTADO|DESGASTADA|DETERIORADO|DETERIORADA|ATASCADO|TRABADO|MAL ESTADO';

const ATENCION_NEGACION_RE = new RegExp(`\\b(NO|SIN|NI|NINGUN|NINGUNA|SI HAY|SI EXISTE|SI EXISTEN|POR SI)\\b( \\w+){0,3}? (${ATENCION_NEG_WORDS})\\b`, 'g');
const ATENCION_NO_REQUIERE_RE = /\bNO (SE )?(REQUIERE|REQUIEREN|NECESITA|NECESITAN|ES NECESARIO|HACE FALTA|FUE NECESARIO|ES REQUERIDO)/g;

const ATENCION_URGENTE_RE = /URGENT|ATENCION INMEDIAT|\bINMEDIAT[OA]\b|PELIGRO|RIESGO|ACCIDENTE|INSEGUR|FUERA DE SERVICIO|PARO (DE (LA )?(PLANTA|LINEA|PRODUCCION|MAQUINA|EQUIPO)|NO PROGRAMADO)|PARADA NO PROGRAMADA/;

const ATENCION_DEFECTO_RE = /\bFALLAS?\b|\bFALLO\b|AVERIA|DANAD|\bROT[OA]S?\b|RUPTURA|FRACTURA|AGRIETAD|RAJAD|\bTRABAD[OA]S?\b|ATASCAD|BLOQUEAD|MAL ESTADO|MALAS CONDICIONES|DETERIOR|DESGASTAD|COLAPS|\bQUEMAD[OA]S?\b|SOBRECALENT|CORTO ?CIRCUITO|CHISPA|DETENID|NO (ESTA|ESTABA) (EN FUNCIONAMIENTO|REGULANDO|FUNCIONANDO|OPERANDO|RESPONDIENDO)|NO (REGULA|RESPONDE|SUBE|CIERRA|ARRANCA|SELLA|CORTA|ENCIENDE|PRENDE|FUNCIONA|OPERA|GIRA|TRABAJA)\b|(CON|MUCHO|BASTANTE|EXCESIVO|PRESENTA|PRESENTAN) (\w+ )?DESGASTE|DESGASTE (EXCESIVO|SEVERO)|DOBLAD|TORCID|DEFORMAD|OXIDAD|CORROID/;

const ATENCION_DEBIL_RE = /\b(PRESENTA|PRESENTAN|PRESENTANDO|TIENE|TIENEN|EVIDENCIA|ENCONTRO|ENCONTRARON|OBSERVA|DETECTA|HAY|EXISTE|EXISTEN|CON|SE VE)\b( \w+){0,3}? (LEVE |PEQUENA |GRAN |ALGUNA )?(FUGAS?|GOTEO|FILTRACION)|\bPROBLEMAS?\b/;

const ATENCION_SEGUIMIENTO_RE = /\bPENDIENTES?\b|QUEDA(N)? POR|POR CAMBIAR|POR REALIZAR|NO SE (REALIZA|REALIZO|PUDO|PUDIERON|LOGRO|EJECUTA|EJECUTO|CONCLUYE|TERMINO|PUEDE)|ADQUIRIR|ADQUISICION|COMPRAR|COMPRA DE|SOLICITAR|SOLICITUD|COTIZ|FALTA DE|FALTANTE|SIN STOCK|NO SE CUENTA|REQUIERE|SE DEBE|DEBERIA|ES NECESARIO|NECESITA|FAVOR|RECOMIENDA|SUGIERE|PLANIFICAR|PROGRAMAR|COORDINAR|AGENDAR|PROXIMA (PARADA|SEMANA|VEZ|INTERVENCION|MANTENIMIENTO)|ENVIAR A|FABRICAR|HAY QUE|HABRIA QUE|\bESTA DE (REALIZAR|PLANIFICAR|ADQUIRIR|COMPRAR|CAMBIAR|REVISAR|HACER|ENVIAR|SOLICITAR|PROGRAMAR|REEMPLAZAR|INSTALAR)/;

const ATENCION_RESUELTO_RE = /\b(CAMBI(A|O|AN|ARON|ADO|ADA|ADOS|ADAS)|REEMPLAZ|REPAR|ARREGL|SOLUCION|CORRIG|SUSTITU|ELIMIN|RETIR|SUELDA|SOLDO|RESUELT|OPERATIV|RECONSTRU|REPUS|BOTA|DESECH|DESCART|DESTAPA|DESATORA)/;

function normalizarAtencion(texto) {
  return texto.normalize('NFD').replace(/[̀-ͯ]/g, '').toUpperCase().replace(/\s+/g, ' ').trim();
}

function sinNegaciones(texto) {
  return texto.replace(ATENCION_NEGACION_RE, ' ').replace(ATENCION_NO_REQUIERE_RE, ' ');
}

// Devuelve 'Urgente', 'Seguimiento' o ''. Un defecto o fuga solo cuenta si en la misma frase no se dice que ya se resolvió.
function nivelAtencion(comentario) {
  if (!comentario || !comentario.trim()) return '';
  const completo = sinNegaciones(normalizarAtencion(comentario));
  if (ATENCION_URGENTE_RE.test(completo)) return 'Urgente';

  let debil = false;
  for (const frase of comentario.split(/[\r\n.;]+/)) {
    if (!frase.trim()) continue;
    const t = sinNegaciones(normalizarAtencion(frase));
    const resuelto = ATENCION_RESUELTO_RE.test(t);
    if (ATENCION_DEFECTO_RE.test(t) && !resuelto) return 'Urgente';
    if (ATENCION_DEBIL_RE.test(t) && !resuelto) debil = true;
  }
  return debil || ATENCION_SEGUIMIENTO_RE.test(completo) ? 'Seguimiento' : '';
}
